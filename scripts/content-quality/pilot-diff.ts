/**
 * npm run content:pilot-diff -- <git-ref> <out.md>
 * Before/after report for the pilot: compares content/pilot/pilot-cq2.json at
 * <git-ref> with the working copy. Lists changed fields per item, plus added
 * and removed items. Rubric scores are left out so the report can sit next
 * to a blind review sheet.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import type { PilotFile, PilotEntry } from "./pilot-lib.js";
import { readPilot } from "./pilot-lib.js";

const [ref = "c70f16b", out = "docs/content-quality-2/review-batch-02/BEFORE_AFTER.md"] = process.argv.slice(2);
const before = JSON.parse(execFileSync("git", ["show", `${ref}:content/pilot/pilot-cq2.json`], { encoding: "utf8" })) as PilotFile;
const after = readPilot("content/pilot/pilot-cq2.json");
const map = (f: PilotFile) => new Map(f.entries.map((e) => [e.item.id, e]));
const B = map(before), A = map(after);
const SKIP_ED = new Set(["rubric", "tone", "playlists", "mechanic", "negativeStem"]);
const show = (v: unknown) => (typeof v === "string" ? v : JSON.stringify(v));
const flat = (e: PilotEntry) => {
  const o: Record<string, string> = {};
  for (const [k, v] of Object.entries(e.item)) if (k !== "review" && k !== "tags") o[k] = show(v);
  for (const [k, v] of Object.entries(e.editorial)) if (!SKIP_ED.has(k)) o[`editorial.${k}`] = show(v);
  o["game"] = e.game;
  return o;
};
const md: string[] = [
  `# Pilot before/after — ${ref} → working copy`, "",
  "Generated by `npm run content:pilot-diff`. Rubric scores are omitted (blind review). Tone, playlist and mechanic tags were added to every item and are not listed per item.", "",
  "Every item remains `provisional`. Nothing here is an approval.", "",
];
const changed = [...A.keys()].filter((id) => B.has(id) && JSON.stringify(flat(B.get(id)!)) !== JSON.stringify(flat(A.get(id)!)));
const added = [...A.keys()].filter((id) => !B.has(id));
const removed = [...B.keys()].filter((id) => !A.has(id));
md.push(`**Summary:** ${changed.length} changed, ${added.length} added, ${removed.length} removed (${B.size} → ${A.size} items).`, "");
md.push("## Changed items", "");
for (const id of changed) {
  const b = flat(B.get(id)!), a = flat(A.get(id)!);
  md.push(`### \`${id}\` (${a["game"]})`, "", "| Field | Before | After |", "|---|---|---|");
  for (const k of new Set([...Object.keys(b), ...Object.keys(a)])) if (b[k] !== a[k]) md.push(`| ${k} | ${(b[k] ?? "—").replace(/\|/g, "\\|")} | ${(a[k] ?? "—").replace(/\|/g, "\\|")} |`);
  md.push("");
}
md.push("## Added items", "");
for (const id of added) {
  const e = A.get(id)!; const it = e.item as Record<string, unknown>;
  md.push(`- \`${id}\` (${e.game}): ${show(it["prompt"] ?? it["event"] ?? it["name"] ?? it["word"] ?? it["quote"])} → **${show(it["answer"] ?? it["year"] ?? `${(it["answers"] as string[] | undefined)?.length ?? ""} answers`)}**${e.editorial.replaces ? ` (replaces ${e.editorial.replaces.join(", ")})` : ""}`);
}
md.push("", "## Removed items", "");
for (const id of removed) md.push(`- \`${id}\` (${B.get(id)!.game})${[...A.values()].find((e) => e.editorial.replaces?.includes(id)) ? ` → replaced by \`${[...A.values()].find((e) => e.editorial.replaces?.includes(id))!.item.id}\`` : ""}`);
writeFileSync(out, md.join("\n") + "\n");
console.log(`wrote ${out}: ${changed.length} changed, ${added.length} added, ${removed.length} removed`);
