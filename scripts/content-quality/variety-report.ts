/**
 * npm run content:variety-sim
 * Writes docs/content-quality-2/E10_ROUND_VARIETY_SIMULATION.md: the bounded
 * variety step (scripts/content-quality/variety.ts) against today's selection
 * (window 0), on Cup-sized and low-content libraries, plus the real pilot.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_CONTENT_DIR, loadContent } from "../../src/content/registry.js";
import { makeLibrary, PLAIN_MECHANICS, PROFILES, prng, selectVaried, simulateCup, type VItem } from "./variety.js";
import type { PilotFile } from "./pilot-lib.js";

const SEEDS = 40;
const SIZES = [10, 12, 20, 40, 80, 140];
const WINDOWS = [0, 3, 8];
const pct = (x: number) => `${Math.round(x * 100)}%`;

const lines: string[] = [
  "# E10 round variety: simulation (generated)",
  "",
  "Generated by `npm run content:variety-sim` (`scripts/content-quality/variety-report.ts`). Do not edit by hand.",
  "",
  `Each row plays a whole Cup: official 10-question games until the no-repeat pool runs out, ${SEEDS} random libraries per row. "Window 0" is today's selector; windows 3 and 8 are the bounded variety step.`,
  "",
  "Columns: **games** = official games the Cup could play (must not change); **rounds with a problem** = share of games breaking the E10 v2 rule; **late** = the same, over the last third of the Cup's games; **look-ahead** = the furthest any pick moved from the seeded order; **repeats** = questions asked twice (must be 0).",
  "",
];
for (const p of PROFILES) {
  lines.push(`## Library: ${p.name}`, "", "| Pool | Window | Games | Rounds with a problem | Late in Cup | Mean problems per round | Look-ahead | Repeats |", "|---|---|---|---|---|---|---|---|");
  for (const size of SIZES) {
    for (const w of WINDOWS) {
      let games = 0, bad = 0, late = 0, mean = 0, la = 0, rep = 0;
      for (let s = 1; s <= SEEDS; s++) {
        const r = simulateCup(makeLibrary(p, size, s), 10, w, s);
        games += r.games; bad += r.gamesWithProblems; late += r.lateGamesWithProblems; mean += r.meanProblems; la = Math.max(la, r.maxLookahead); rep += r.repeats;
      }
      lines.push(`| ${size} | ${w === 0 ? "0 (today)" : w} | ${(games / SEEDS).toFixed(0)} | ${pct(bad / SEEDS)} | ${pct(late / SEEDS)} | ${(mean / SEEDS).toFixed(2)} | ${la} | ${rep} |`);
    }
  }
  lines.push("");
}

// The real pilot: its 17 tagged quiz-style Trivia items, one 10-question game.
const pilot = JSON.parse(readFileSync(join(DEFAULT_CONTENT_DIR, "pilot", "pilot-cq2.json"), "utf8")) as PilotFile;
const real: VItem[] = pilot.entries.filter((e) => e.game === "trivia").map((e) => ({
  id: e.item.id as string, difficulty: e.item.difficulty as 1 | 2 | 3, category: String(e.item.category),
  tags: { ...(e.editorial.mechanic ? { mechanic: e.editorial.mechanic } : {}), ...(e.editorial.negativeStem ? { negative: true } : {}) },
}));
lines.push(`## The real pilot (${real.length} Trivia items, one 10-question game, ${SEEDS * 5} seeds)`, "", "| Window | Rounds with a problem | Mean problems |", "|---|---|---|");
for (const w of WINDOWS) {
  let bad = 0, mean = 0;
  const n = SEEDS * 5;
  for (let s = 1; s <= n; s++) { const r = selectVaried(real, 10, prng(s), w); bad += r.problems.length > 0 ? 1 : 0; mean += r.problems.length; }
  lines.push(`| ${w === 0 ? "0 (today)" : w} | ${pct(bad / n)} | ${(mean / n).toFixed(2)} |`);
}
lines.push("");

// The real library, now tagged with question formats (E10 metadata). Every
// item is still provisional or legacy: re-run after editorial review, when the
// approved pool is known (owner direction 2026-11-07).
const lib = loadContent(DEFAULT_CONTENT_DIR);
lines.push("## The real library (tagged 2026-11-07; provisional, not yet editorially reviewed)", "",
  "Pool: every official-eligibility item that is not rejected, i.e. what official play would draw on once approved. Whole Cups of 10-question games, " + SEEDS + " seeds. **Re-run after editorial review**: the approved pool may differ.", "",
  "| Game | Pool | Twist-format items | Window | Games | Rounds with a problem | Repeats |", "|---|---|---|---|---|---|---|");
for (const g of ["trivia", "geography", "who-said-that"] as const) {
  const items: VItem[] = (lib.byGame.get(g) ?? []).filter((li) => li.item.eligibility === "official" && li.status !== "rejected").map((li) => {
    const it = li.item as { id: string; difficulty: 1 | 2 | 3; category: string; mechanic?: string; negativeStem?: boolean };
    return { id: it.id, difficulty: it.difficulty, category: it.category, tags: { ...(it.mechanic ? { mechanic: it.mechanic } : {}), ...(it.negativeStem ? { negative: true } : {}) } };
  });
  const twist = items.filter((x) => x.tags.mechanic && !PLAIN_MECHANICS.has(x.tags.mechanic)).length;
  for (const w of [0, 3]) {
    let games = 0, bad = 0, rep = 0;
    for (let s = 1; s <= SEEDS; s++) { const r = simulateCup(items, 10, w, s); games += r.games; bad += r.gamesWithProblems; rep += r.repeats; }
    lines.push(`| ${g} | ${items.length} | ${twist} | ${w === 0 ? "0 (today)" : w} | ${(games / SEEDS).toFixed(0)} | ${pct(bad / SEEDS)} | ${rep} |`);
  }
}
lines.push("");
writeFileSync(join(DEFAULT_CONTENT_DIR, "..", "docs", "content-quality-2", "E10_ROUND_VARIETY_SIMULATION.md"), lines.join("\n"));
console.log("wrote docs/content-quality-2/E10_ROUND_VARIETY_SIMULATION.md");
