/**
 * npm run content:audit — merge the editorial verdicts
 * (docs/content-quality-2/audit-verdicts.json) with the live library and
 * write docs/content-quality-2/LIBRARY_AUDIT_TABLE.md. Facts a machine can
 * check (input range) are added automatically. Nothing here changes an
 * item's review status.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadContent, officialEligible } from "../../src/content/registry.js";
import { connectionsSolutions, enterable } from "./pilot-lib.js";

type Verdict = { verdict: "KEEP" | "REVISE" | "REPLACE" | "REJECT"; codes: string[]; note: string; suggestedDifficulty?: number };
const root = join(import.meta.dirname, "..", "..");
const src = JSON.parse(readFileSync(join(root, "docs/content-quality-2/audit-verdicts.json"), "utf8")) as { defaults: Record<string, Verdict>; items: Record<string, Verdict>; connectionsOverlaps: Record<string, Record<string, string[]>> };
const lib = loadContent();
const today = new Date().toISOString().slice(0, 10);
const rows: string[] = [];
const missing: string[] = [];
const unknown = Object.keys(src.items).filter((id) => !lib.items.has(id));
const tally = new Map<string, Record<string, number>>();
const codeCount = new Map<string, number>();
let rangeOfficial = 0;
const multiSolution: string[] = [];
for (const [gameId, items] of [...lib.byGame].sort(([a], [b]) => a.localeCompare(b))) {
  rows.push(`\n## ${gameId}\n\n| Item | Status | Diff | Verdict | Codes | Note |\n|---|---|---|---|---|---|`);
  for (const li of items) {
    const v: Verdict | undefined = src.items[li.item.id] ?? src.defaults[gameId];
    if (!v) { missing.push(li.item.id); continue; }
    const codes = [...v.codes.filter(Boolean)];
    const it = li.item as unknown as Record<string, unknown>;
    if (gameId === "guess-the-year" || gameId === "closest-wins") {
      const ans = Number(gameId === "guess-the-year" ? it["year"] : it["answer"]);
      if (!enterable(gameId, ans) && !codes.includes("INPUT-RANGE")) codes.push("INPUT-RANGE");
      if (!enterable(gameId, ans) && officialEligible(li, today)) rangeOfficial++;
    }
    if (gameId === "word-connections") {
      const n = connectionsSolutions(it["groups"] as { name: string; words: string[] }[], src.connectionsOverlaps[li.item.id] ?? {}).length;
      if (n !== 1) { codes.push("ALTERNATIVE-SOLUTION"); multiSolution.push(`${li.item.id} (${n})`); }
    }
    for (const c of codes) codeCount.set(c, (codeCount.get(c) ?? 0) + 1);
    const t = tally.get(gameId) ?? { KEEP: 0, REVISE: 0, REPLACE: 0, REJECT: 0 };
    t[v.verdict]!++; tally.set(gameId, t);
    const d = v.suggestedDifficulty && v.suggestedDifficulty !== li.item.difficulty ? `${li.item.difficulty}→${v.suggestedDifficulty}` : String(li.item.difficulty);
    rows.push(`| ${li.item.id} | ${li.status} | ${d} | ${v.verdict} | ${codes.join(", ")} | ${v.note.replace(/\|/g, "/")} |`);
  }
}
const head = ["# Library audit — per-item table (generated)", "", "Generated by `npm run content:audit` from `audit-verdicts.json` and the live packs. These are editorial triage verdicts by Claude, not human review. No item's status was changed.", "", "| Game | Items | KEEP | REVISE | REPLACE | REJECT |", "|---|---|---|---|---|---|"];
let all = { n: 0, KEEP: 0, REVISE: 0, REPLACE: 0, REJECT: 0 };
for (const [g, t] of [...tally].sort(([a], [b]) => a.localeCompare(b))) {
  const n = t.KEEP! + t.REVISE! + t.REPLACE! + t.REJECT!;
  head.push(`| ${g} | ${n} | ${t.KEEP} | ${t.REVISE} | ${t.REPLACE} | ${t.REJECT} |`);
  all = { n: all.n + n, KEEP: all.KEEP + t.KEEP!, REVISE: all.REVISE + t.REVISE!, REPLACE: all.REPLACE + t.REPLACE!, REJECT: all.REJECT + t.REJECT! };
}
head.push(`| **all** | **${all.n}** | **${all.KEEP}** | **${all.REVISE}** | **${all.REPLACE}** | **${all.REJECT}** |`, "", "Finding codes (an item can have several): " + [...codeCount].sort((a, b) => b[1] - a[1]).map(([c, n]) => `${c} ${n}`).join(", ") + ".", "", `Official-eligible items whose answer can't be entered today: **${rangeOfficial}**.`, "", `Word Connections boards with more than one solution (given the overlaps declared in audit-verdicts.json): ${multiSolution.length ? multiSolution.join(", ") : "none"}.`);
writeFileSync(join(root, "docs/content-quality-2/LIBRARY_AUDIT_TABLE.md"), [...head, ...rows, ""].join("\n"));
console.log(head.slice(4).join("\n"));
if (missing.length || unknown.length) {
  if (missing.length) console.error(`No verdict for: ${missing.join(", ")}`);
  if (unknown.length) console.error(`Verdicts for unknown items: ${unknown.join(", ")}`);
  process.exit(1);
}
