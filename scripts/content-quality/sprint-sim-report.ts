/** npm run content:sprint-sim — regenerate the E2 v3 set-size tables (deterministic; seed 1). */
import { writeFileSync } from "node:fs";
import { simulate, suitable, POLICY } from "./sprint-sim.js";

export const SCENARIOS = [
  { key: "even", label: "Even recall: every member equally likely, everyone knows all", skew: 0, depth: 0, maxKnown: 1 },
  { key: "famous-first", label: "Famous-first: well-known members come to mind first; most players know most members", skew: 1.0, depth: 0.25 },
  { key: "obscure-tail", label: "Famous-first with an obscure tail: many members known only to some players", skew: 1.0, depth: 0.6 },
  { key: "dominant", label: "Dominant few / recited in order: a handful of members are written by almost everyone", skew: 1.6, depth: 0.25 },
] as const;

export const PLAYERS = [4, 5, 6, 7, 8, 9, 10];
export const SIZES = [10, 12, 13, 15, 18, 20, 24, 27, 30, 35, 40, 45, 50, 54, 60, 70, 80, 100, 118, 151, 195];

function minSize(players: number, s: (typeof SCENARIOS)[number]): number | null {
  for (const n of SIZES) {
    const r = simulate({ setSize: n, players, skew: s.skew, depth: s.depth, maxKnown: "maxKnown" in s ? s.maxKnown : undefined, rounds: 3000 });
    if (suitable(r)) return n;
  }
  return null;
}

const pct = (x: number) => `${Math.round(x * 100)}%`;
const lines: string[] = [];
lines.push("# E2 v3 — Category Sprint set-size simulation (generated)", "");
lines.push("Generated by `npm run content:sprint-sim` (scripts/content-quality/sprint-sim.ts, seed 1, 3,000 simulated rounds per cell). Do not edit by hand.", "");
lines.push(`Suitability policy: at most ${pct(POLICY.maxShort)} of players run out of valid answers; between ${pct(POLICY.minUnique)} and ${pct(POLICY.maxUnique)} of valid answers earn the uniqueness bonus; at most ${pct(POLICY.maxNoBonusRounds)} of rounds award no bonus to anyone. Each player gives up to 5 answers; scoring is today's (20 + 20 if unique).`, "");
lines.push("## Minimum suitable set size, by recall profile and player count", "");
lines.push(`| Profile | ${PLAYERS.map((p) => `${p} players`).join(" | ")} |`, `|---|${PLAYERS.map(() => "---").join("|")}|`);
for (const s of SCENARIOS) lines.push(`| ${s.label} | ${PLAYERS.map((p) => minSize(p, s) ?? `>${SIZES.at(-1)}`).join(" | ")} |`);
lines.push("", "The sizes tried were " + SIZES.join(", ") + "; a cell shows the first size that met the policy.", "");
lines.push("## Detail: uniqueness rate (share of valid answers that earn the bonus) / players short of 5 valid answers", "");
for (const s of SCENARIOS) {
  lines.push(`### ${s.label}`, "", `| Set size | ${PLAYERS.map((p) => `${p}p`).join(" | ")} |`, `|---|${PLAYERS.map(() => "---").join("|")}|`);
  for (const n of [12, 13, 15, 20, 27, 30, 40, 50, 54, 80, 118]) {
    lines.push(`| ${n} | ${PLAYERS.map((p) => {
      const r = simulate({ setSize: n, players: p, skew: s.skew, depth: s.depth, maxKnown: "maxKnown" in s ? s.maxKnown : undefined, rounds: 3000 });
      return `${pct(r.uniqueRate)} / ${pct(r.shortRate)}${suitable(r) ? " ✓" : ""}`;
    }).join(" | ")} |`);
  }
  lines.push("");
}
writeFileSync("docs/content-quality-2/E2_SET_SIZE_SIMULATION.md", lines.join("\n") + "\n");
